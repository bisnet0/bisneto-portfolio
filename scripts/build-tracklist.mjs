/**
 * Generates src/content/tracklist.ts from the audio folder.
 *
 * Any file dropped into public/audio/soft-disco is picked up on the next `npm run dev`
 * or `npm run build`. Display names hide the download markers (`_spotdown.org`) and
 * turn underscores into spaces, so the player never shows scraper noise.
 */
import { readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const AUDIO_DIR = join(process.cwd(), 'public', 'audio', 'soft-disco')
const OUT_FILE = join(process.cwd(), 'src', 'content', 'tracklist.ts')
const EXTENSIONS = /\.(mp3|m4a|ogg|wav|aac|flac)$/i

const displayName = (filename) => {
  const base = filename.replace(EXTENSIONS, '')
  return base
    .replace(/[-_]?spotdown(\.org)?/gi, '')
    .replace(/[-_]?www\.[a-z0-9.-]+/gi, '')
    .replace(/_+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim() || base
}

const files = (await readdir(AUDIO_DIR).catch(() => [])).filter((file) => EXTENSIONS.test(file))

const tracks = files
  .sort((a, b) => a.localeCompare(b, 'pt-BR'))
  .map((file) => ({
    title: displayName(file),
    src: `/audio/soft-disco/${encodeURIComponent(file)}`,
  }))

const banner = `// Generated by scripts/build-tracklist.mjs — do not edit by hand.
// Drop new files into public/audio/soft-disco and run \`npm run tracklist\`.

export interface Track {
  title: string
  src: string
}

export const tracklist: Track[] = ${JSON.stringify(tracks, null, 2)}
`

await writeFile(OUT_FILE, banner, 'utf8')
console.log(`tracklist: ${tracks.length} tracks -> src/content/tracklist.ts`)
